function withForkMessages(
  plugin: LocalePlugin,
  patch: (typeof FORK_MESSAGE_PATCHES)[Locale],
): LocalePlugin {
  const messages = { ...plugin.messages, ...patch.set };
  for (const key of patch.remove) delete messages[key];
  return { ...plugin, messages };
}

